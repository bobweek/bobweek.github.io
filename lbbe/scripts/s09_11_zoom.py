"""
Slides 09-11 -- guild -> nectar theft -> network -> within-guild projection ->
niches -> the guild as a community.

One scene and ONE camera for frames 09a, 09b, 10, 11a and 11b: every node sits
at the same place on every slide, so stepping through them reads as one
picture being built up and then redrawn, not as five pictures.

  09a  the fly and its guild of long-tubed plants
  09b  + Babiana thunbergii, a sunbird flower the fly robs (with the photo)
  10   + the other pollinators and plants: the network around the pair
  11a  the links between guilds recede; pollinators that share plants are
       joined by arcs (the one-guild projection)
  11b  the plant row becomes a resource axis with one utilisation curve per
       pollinator
  11c  the same guild on a circle, with competition coefficients and selection
       gradients for every pair (its own layout)

What is real and what is schematic
----------------------------------
Real:
  * the focal pair, Moegistorhynchus longirostris and Lapeirousia anceps;
  * the six guild plants in 09a/09b and their order by tube length (Goldblatt
    & Manning 2000, Table 2); the guild has at least 20 members (Manning &
    Goldblatt 1997);
  * the fly takes nectar from Babiana thunbergii, a sunbird flower, almost
    never touching anthers or stigma (Pauw et al. 2009, Fig. 5: the photo);
  * in frame 10, the two tabanids that share the guild and the plants they
    share with the fly: Philoliche gulosa (Tritonia crispa, Lapeirousia
    fabricii, L. anceps) and P. rostrata (Ixia paniculata) (Goldblatt &
    Manning 2000, Table 2), and the malachite sunbird on B. thunbergii.
Guild sizes quoted on frame 10: "six or seven fly species" (Goldblatt &
Manning 2000, text); about 35 plant species with pollination records in their
Table 2 for this guild (a scripted count of the table's text); at least 20 for
M. longirostris (Manning & Goldblatt 1997).
Schematic: every other node and link, generated by one trait-matching rule (a
pollinator visits plants whose rank on the trait axis lies within its range),
which is what lets the bipartite links turn into utilisation curves in 11b.

`frame_pair` (the to-scale portrait of the fly and flower) is kept as an
extra, s09x_pair_portrait; it is not part of the sequence.
"""
