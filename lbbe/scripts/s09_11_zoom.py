def adjacency():
    A = np.zeros((len(POLL), NP), int)
    for i, (_, c, h) in enumerate(POLL):
        for j in range(NP):
            if abs(j - c) <= h:
                A[i, j] = 1
    A[FLY, :8] = 0                      # the guild is the long-tubed plants
    A[ROSTRATA, 11] = 1                 # P. rostrata on Ixia paniculata
    return A


